// Lists the open world's hidden places - every well, grotto and cave behind a
// waterfall (infterrain's special places - fixed seed, so the same every run)
// - and where in each one loot can be left: infterrain's stash spots, open
// floor its builders keep their stones, crystals and stalagmites off.
// recources/hiddenHoards.ts fills them. A grotto has ore spots as well, in the
// maze inside its crag - recources/ores.ts puts a vein at each.
//
//   node generate-datas/genHiddenPlaces.mjs   (from tcp/)
//
// Writes recources/hiddenPlaces.ts. Re-run it if infterrain's places ever
// change, or the loot will float where a place used to be. It reads the
// client's linked copy of infterrain (client/node_modules/infterrain/dist), so
// build the module first (npm run build in it).
import { pathToFileURL, fileURLToPath } from "node:url"
import { register } from "node:module"
import { writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"

const here = dirname(fileURLToPath(import.meta.url))
register(pathToFileURL(resolve(here, "dirImportHook.mjs")).href)
const inf = await import(pathToFileURL(resolve(here, "../../client/node_modules/infterrain/dist/infterrain.js")).href)
const { listSites, siteStashSpots, terrainHeight, SPAWN_X, SPAWN_Z } = inf
if (!siteStashSpots) throw new Error("this infterrain build has no siteStashSpots - build the module first")

// as far out as the open world's enemies and ores go (enemyDetails.ts, genCrystalHollows.mjs)
const MAX_DIST = 3200
const KINDS = ["well", "grotto", "falls"]
const r2 = n => Math.round(n * 100) / 100

const places = []
let worstGround = 0
for (const site of listSites(SPAWN_X, SPAWN_Z, MAX_DIST)) {
    if (!KINDS.includes(site.kind)) continue
    const all = siteStashSpots(site.key).map(s => ({ name: s.name, x: r2(s.x), y: r2(s.y), z: r2(s.z) }))
    const spots = Object.fromEntries(all.map(s => [s.name, s]))
    if (!spots.chest || !spots.weapon || !spots.patch) throw new Error(`${site.key}: missing a stash spot`)
    const ores = all.filter(s => /^ore\d+$/.test(s.name))
    // the cave behind the falls and the grotto's maze have no floor of their
    // own - you walk on the ground there, which the place flattens. Checked, as
    // the client trusts these heights instead of looking for the ground (and
    // grounds the ores on the terrain, which had better be that floor)
    if (site.kind === "falls" || site.kind === "grotto")
        for (const s of all) worstGround = Math.max(worstGround, Math.abs(terrainHeight(s.x, s.z) - s.y))
    places.push({ key: site.key, kind: site.kind, distance: Math.round(site.distance), chest: spots.chest, weapon: spots.weapon, patch: spots.patch, ores })
}
if (worstGround > 0.05) throw new Error(`a cave's floor is ${worstGround.toFixed(2)} off the ground under it`)

const spot = s => `{ x: ${s.x}, y: ${s.y}, z: ${s.z} }`
const lines = places.map(p =>
    `    { key: "${p.key}", kind: "${p.kind}", distance: ${p.distance},\n` +
    `      chest: ${spot(p.chest)}, weapon: ${spot(p.weapon)}, patch: ${spot(p.patch)},\n` +
    `      ores: [${p.ores.map(spot).join(", ")}] },`)
writeFileSync(resolve(here, "../recources/hiddenPlaces.ts"),
`// GENERATED by generate-datas/genHiddenPlaces.mjs - the open world's wells,
// grottos and caves behind the falls (infterrain's special places), nearest
// the spawn first, and the open floor in each where hiddenHoards.ts leaves its
// loot - and in a grotto's maze, where ores.ts puts its veins. y is that floor
// - down a well it is far below the ground over it, so the client takes it as
// it is (exactY) instead of grounding the loot on the terrain.
export type ThiddenSpot = { x: number, y: number, z: number }
export type ThiddenPlace = {
    key: string
    kind: "well" | "grotto" | "falls"
    // from the spawn
    distance: number
    chest: ThiddenSpot
    weapon: ThiddenSpot
    patch: ThiddenSpot
    // a grotto's ore spots - none anywhere else
    ores: ThiddenSpot[]
}
export const HIDDEN_PLACES: ThiddenPlace[] = [
${lines.join("\n")}
]
`)
const by = places.reduce((n, p) => (n[p.kind] = (n[p.kind] ?? 0) + 1, n), {})
console.log(`${places.length} hidden places within ${MAX_DIST} of the spawn:`, by)
console.log(`falls caves' and grottos' floors within ${worstGround.toFixed(3)} of the ground, ${places.reduce((n, p) => n + p.ores.length, 0)} ore spots`)
places.forEach(p => console.log(`  ${p.kind.padEnd(6)} ${p.key.padEnd(14)} ${String(p.distance).padStart(5)} from spawn, floor y ${p.chest.y}`))
