// Picks where the open world's mineable crystals stand: spots inside the
// Crystal Hollows biome (infterrain's biome map is deterministic - fixed seed),
// clear of roads, water, rivers, the special places and steep ground.
//
//   node generate-datas/genCrystalHollows.mjs   (from tcp/)
//
// Writes recources/crystalHollows.ts. Re-run it if infterrain's biome map ever
// changes, or the crystals will stand outside their hollows. It reads the
// client's linked copy of infterrain (client/node_modules/infterrain/dist), so
// build the module first (npm run build in it).
import { pathToFileURL, fileURLToPath } from "node:url"
import { register } from "node:module"
import { writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"

const here = dirname(fileURLToPath(import.meta.url))
register(pathToFileURL(resolve(here, "dirImportHook.mjs")).href)
const inf = await import(pathToFileURL(resolve(here, "../../client/node_modules/infterrain/dist/infterrain.js")).href)
const { biomeWeightsAt, inSiteFootprint, roadDistance, inRiverChannel, surfaceHeight, WATER_LEVEL, SPAWN_X, SPAWN_Z } = inf

const MIN_DIST = 700       // the hub and its roads are tamed ground
const MAX_DIST = 3200
const SPACING = 40         // between any two
const PER_HOLLOW = 5       // within CLUSTER of each other - a grove of them
const CLUSTER = 300
const MAX_SPOTS = 45       // every deposit is a mesh, a body and a bar on every client
const STEP = 24

const candidates = []
for (let x = SPAWN_X - MAX_DIST; x <= SPAWN_X + MAX_DIST; x += STEP)
    for (let z = SPAWN_Z - MAX_DIST; z <= SPAWN_Z + MAX_DIST; z += STEP) {
        const d = Math.hypot(x - SPAWN_X, z - SPAWN_Z)
        if (d < MIN_DIST || d > MAX_DIST) continue
        if (biomeWeightsAt(x, z).crystal < 0.85) continue
        if (roadDistance(x, z) < 40 || inRiverChannel(x, z, 14) || inSiteFootprint(x, z, 10)) continue
        const g = surfaceHeight(x, z)
        if (g < WATER_LEVEL + 1.5) continue
        const slope = Math.max(Math.abs(surfaceHeight(x + 2, z) - g), Math.abs(surfaceHeight(x, z + 2) - g)) / 2
        if (slope > 0.3) continue
        candidates.push({ x, z, d })
    }
candidates.sort((a, b) => a.d - b.d)

const spots = []
for (const c of candidates) {
    if (spots.length >= MAX_SPOTS) break
    if (spots.some(s => Math.hypot(s.x - c.x, s.z - c.z) < SPACING)) continue
    if (spots.filter(s => Math.hypot(s.x - c.x, s.z - c.z) < CLUSTER).length >= PER_HOLLOW - 1) continue
    spots.push({ x: Math.round(c.x), z: Math.round(c.z), d: Math.round(c.d) })
}

const lines = spots.map(s => `    { x: ${s.x}, z: ${s.z} },   // ${s.d} from the spawn`)
writeFileSync(resolve(here, "../recources/crystalHollows.ts"),
`// GENERATED by generate-datas/genCrystalHollows.mjs - spots inside infterrain's
// Crystal Hollows biome where a mineable crystal ("hollow" vein, ores.ts)
// stands. y stays 0 like every open-world ore: the client grounds each one.
export const CRYSTAL_HOLLOW_SPOTS: { x: number, z: number }[] = [
${lines.join("\n")}
]
`)
console.log(`${candidates.length} candidate spots in the hollows, ${spots.length} chosen:`)
spots.forEach(s => console.log(`  ${s.x}, ${s.z}  (${s.d} from spawn)`))
